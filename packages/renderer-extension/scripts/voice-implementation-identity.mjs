export const GENERATED_REVISION_RELATIVE =
  "src/renderer-voice-implementation-revision.generated.ts";

export function generatedRevisionSource(revision) {
  return `/** Generated by voice-implementation-identity.mjs. Do not edit. */\nexport const VOICE_IMPLEMENTATION_REVISION = ${JSON.stringify(revision)};\n`;
}

function localSpecifiers(source) {
  const specs = [];
  for (const line of source.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (trimmed.startsWith("import type ") || trimmed.startsWith("export type ")) continue;
    const from = trimmed.match(/^(?:import|export)\s.+\sfrom\s+["'](\.\/[^"']+)["']/);
    if (from) specs.push(from[1]);
    const side = trimmed.match(/^import\s+["'](\.\/[^"']+)["']/);
    if (side) specs.push(side[1]);
  }
  return specs;
}

function resolveLocal(importerRelative, specifier) {
  const withTs = specifier.replace(/\.js$/u, ".ts");
  const resolved = path.posix.normalize(
    path.posix.join(path.posix.dirname(importerRelative), withTs),
  );
  if (!resolved.startsWith("src/") || resolved.includes("..")) return null;
  if (resolved === GENERATED_REVISION_RELATIVE) return null;
  return resolved;
}

export async function listVoiceImplementationSourceFiles(packageRoot, replacements = {}) {
  const pending = [...VOICE_IMPLEMENTATION_SEED_FILES];
  const seen = new Set();
  while (pending.length > 0) {
    const relative = pending.shift();
    if (!relative || seen.has(relative)) continue;
    seen.add(relative);
    const source = Object.hasOwn(replacements, relative)
      ? replacements[relative]
      : await readFile(path.join(packageRoot, relative), "utf8");
    for (const specifier of localSpecifiers(source)) {
      const next = resolveLocal(relative, specifier);
      if (next && !seen.has(next)) pending.push(next);
    }
  }
  return [...seen].sort();
}

/** @deprecated Use listVoiceImplementationSourceFiles; kept as the seed list for coverage diffs. */
export const VOICE_IMPLEMENTATION_SOURCE_FILES = VOICE_IMPLEMENTATION_SEED_FILES;

export async function computeVoiceImplementationIdentity(packageRoot, replacements = {}) {
  const files = await listVoiceImplementationSourceFiles(packageRoot, replacements);
  const hash = createHash("sha256");
  for (const relative of files) {
    const content = Object.hasOwn(replacements, relative)
      ? replacements[relative]
      : await readFile(path.join(packageRoot, relative), "utf8");
    hash.update(relative);
    hash.update("\0");
    hash.update(content);
    hash.update("\n");
  }
  return hash.digest("hex").slice(0, 16);
}

export async function writeVoiceImplementationRevision(packageRoot) {
  const revision = await computeVoiceImplementationIdentity(packageRoot);
  await writeFile(
    path.join(packageRoot, GENERATED_REVISION_RELATIVE),
    generatedRevisionSource(revision),
  );
  return revision;
}
